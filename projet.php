            <h2>Le commencement</h2>
            <p class="odd">Une <strong>ressourcerie</strong> est une structure complexe. Nous sommes actuellement dans la phase initiale du projet, dont la première étape a été de créer notre <strong>association Ressource’Brie</strong>.
Le prochain défi sera de trouver un local, qui devra permettre de <strong>stocker</strong> et de <strong>vendre</strong> les objets dans un premier temps, puis de les <strong>réparer</strong> dans un second temps. Pour qu’un projet de <strong>ressourcerie</strong> soit viable, le local doit faire l’objet d’une mise à disposition subventionnée ou idéalement gratuite.
            </p>
            <p class="even"> Vous l’aurez compris, il s’agit d’un projet de longue haleine. Outre la recherche d’un local et les premières actions de <strong>sensibilisation</strong> qui seront menées, les mois à venir vont être consacrés à la communication autour de ce projet. Pour cela, des évènements ponctuels seront organisés. Ils intègreront des <strong>ateliers collaboratifs</strong> et ludiques sur le thème de l’<strong>environnement</strong>,
            avec un seul objectif : favoriser l’échange.
            </p>
            <p class="odd"> Monter une structure de type <strong>ressourcerie</strong> implique également de constituer des dossiers de recherche de subventions.
Si vous avez des connaissances de subventions en lien avec ce type de projet, n’hésitez pas à nous l’indiquer par mail, ou via notre <a href="contact.php">formulaire</a>. Merci d’avance pour votre contribution !

            </p>
            <h2>Une fois le local obtenu</h2>
            <p class="even">Ainsi, de manière évidente, l’acquisition d’un local sera une étape clé de ce projet. Nous avons beaucoup échangé avec d’autres <strong>ressourceries</strong> : bien souvent, les locaux nécessitent une forte réhabilitation avant de pouvoir être accessibles au public, avec une mise en conformité par rapport aux normes en vigueur. Quand nous aurons trouvé un local, nous aurons donc besoin d’un maximum de bénévoles
            pour la réalisation de ces travaux !
            </p>
            
