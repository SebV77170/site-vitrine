            <h2>L'évolution future</h2>
            <p class="even">Les bénévoles seront la clé de voûte de ce projet pour <strong>recevoir</strong>, <strong>trier</strong>, <strong>réparer</strong> et <strong>revendre</strong> les objets. Dès que l’activité sera lancée, nous espérons pouvoir recruter rapidement un ou plusieurs salariés afin de permettre une ouverture régulière de la structure. Bien évidemment, les bénévoles conserveront une place
            primordiale dans cette organisation. </p>
            <p class="odd">L’ultime objectif sera de mettre en place une véritable structure pour <strong>réparer les objets</strong>, devenant ainsi un vrai <strong>centre de traitement alternatif des déchets</strong>. Les objets seront ainsi <strong>ré-employés</strong> dans leur fonction initiale ou <strong>revalorisés</strong> pour
            leur donner une nouvelle fonction. Avec toujours le même objectif : réduire la part des <strong>déchets recyclés</strong>, <strong>enfouis</strong> ou <strong>incinérés</strong>.
